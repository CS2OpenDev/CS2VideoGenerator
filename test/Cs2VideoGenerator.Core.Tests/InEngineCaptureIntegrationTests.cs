#region

using System.Globalization;
using Cs2VideoGenerator.Core.Capture;
using Cs2VideoGenerator.Core.Services;
using Cs2VideoGenerator.Core.Tests.TestSupport;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.Extensions.Options;
using Xunit;

#endregion

namespace Cs2VideoGenerator.Core.Tests;

/// <summary>
///     The in-engine provider against the real ffmpeg, which is the only way to find out whether the
///     frames it pipes are actually decodable and whether the audio it muxes lines up. Skipped where
///     ffmpeg is not installed, the same gate <see cref="FfmpegServiceTests" /> uses.
/// </summary>
/// <remarks>
///     What these do not establish is that CS2 writes what is fed in here - the frames are generated by
///     ffmpeg, not by the engine. Closing that gap needs a machine with the game.
/// </remarks>
public class InEngineCaptureIntegrationTests : IDisposable
{
    private readonly TempDir _audio = new("csvg-inengine-int-audio-");
    private readonly TempDir _output = new("csvg-inengine-int-output-");
    private readonly TempDir _source = new("csvg-inengine-int-source-");
    private readonly TempDir _staging = new("csvg-inengine-int-staging-");

    public void Dispose()
    {
        _staging.Dispose();
        _audio.Dispose();
        _output.Dispose();
        _source.Dispose();
        GC.SuppressFinalize(this);
    }

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    /// <summary>
    ///     A JPEG frame dump piped through a real encode and mux, with the result probed back. JPEG is
    ///     self-delimiting, so this is the path that needs no record length.
    /// </summary>
    [Fact]
    public async Task JpgFrames_EncodeAndMuxIntoAPlayableClip()
    {
        FfmpegTools.SkipUnlessAvailable();

        const int frameCount = 48;
        const int frameRate = 24;

        FfmpegTools.GenerateFrameSequence(_source.Path, "jpg", frameCount, frameRate);
        FfmpegTools.GenerateSilentWav(Path.Combine(_source.Path, "csvg_000.wav"), frameCount / (double)frameRate);

        CaptureResult result = await RunAsync(
            new InEngineCaptureConfiguration
            {
                FrameFormat = InEngineFrameFormat.Jpg,
                FrameConsumerPollMs = 20,
                IntermediateEncoder = ImagePipeEncoder.X264,
                EngineOutput = new InEngineEngineOutput { FirstFrameNumber = 1 }
            },
            frameRate);

        Assert.True(result.Success, result.ErrorMessage);
        Assert.Equal(frameCount, result.TotalFrames);
        Assert.Equal(TimeSpan.FromSeconds(frameCount / (double)frameRate), result.Duration);

        Assert.Equal(frameCount, FfmpegTools.CountVideoFrames(result.OutputFilePath));
        Assert.Equal($"{frameRate}/1", FfmpegTools.VideoFrameRate(result.OutputFilePath));
        Assert.Equal(1, FfmpegTools.StreamCount(result.OutputFilePath, "a"));
    }

    /// <summary>
    ///     The Targa path, which only works because the record length tells ffmpeg where each frame
    ///     ends: it has no Targa parser, and a bare stream of them decodes into nothing at all.
    /// </summary>
    [Fact]
    public async Task TgaFrames_EncodeThroughTheConfiguredRecordLength()
    {
        FfmpegTools.SkipUnlessAvailable();

        const int frameCount = 24;
        const int frameRate = 24;

        FfmpegTools.GenerateFrameSequence(_source.Path, "tga", frameCount, frameRate);
        int recordLength = (int)new FileInfo(Directory.GetFiles(_source.Path, "*.tga").Order().First()).Length;

        CaptureResult result = await RunAsync(
            new InEngineCaptureConfiguration
            {
                FrameFormat = InEngineFrameFormat.Tga,
                FrameConsumerPollMs = 20,
                IntermediateEncoder = ImagePipeEncoder.X264,
                MissingAudioBehavior = MissingAudioBehavior.WarnAndContinue,
                EngineOutput = new InEngineEngineOutput
                {
                    FirstFrameNumber = 1,
                    TgaFrameSizeBytes = recordLength
                }
            },
            frameRate);

        Assert.True(result.Success, result.ErrorMessage);
        Assert.Equal(frameCount, result.TotalFrames);
        Assert.Equal(frameCount, FfmpegTools.CountVideoFrames(result.OutputFilePath));
    }

    /// <summary>
    ///     The failure this whole arrangement exists to make loud. Run-length-encoded Targa frames vary
    ///     in size, so no fixed record length can be right - and piping them anyway would produce a file
    ///     that decodes into noise without erroring. The clip has to fail instead, and say what size it
    ///     actually saw.
    /// </summary>
    [Fact]
    public async Task RunLengthEncodedTgaFrames_FailTheClipInsteadOfProducingNoise()
    {
        FfmpegTools.SkipUnlessAvailable();

        const int frameRate = 24;

        // The fixture normally disables run-length encoding precisely because a Targa pipe needs frames
        // of one size. Here it is the point - and the source has to be one whose frames compress
        // differently, because a pattern that happens to compress identically is the case that makes a
        // fixed record length look fine right up until it does not.
        FfmpegTools.Run("ffmpeg",
        [
            "-y", "-hide_banner", "-loglevel", "error",
            "-f", "lavfi", "-i", $"testsrc2=duration=1:size=160x120:rate={frameRate}",
            "-vcodec", "targa", "-rle", "1",
            "-f", "image2", Path.Combine(_source.Path, "frame%04d.tga")
        ]);

        string[] sources = [.. Directory.GetFiles(_source.Path, "*.tga").Order()];
        long[] sizes = [.. sources.Select(path => new FileInfo(path).Length)];
        Assert.True(sizes.Distinct().Count() > 1,
            "this test needs run-length-encoded frames of differing sizes to mean anything");

        CaptureResult result = await RunAsync(
            new InEngineCaptureConfiguration
            {
                FrameFormat = InEngineFrameFormat.Tga,
                FrameConsumerPollMs = 20,
                IntermediateEncoder = ImagePipeEncoder.X264,
                MissingAudioBehavior = MissingAudioBehavior.WarnAndContinue,
                EngineOutput = new InEngineEngineOutput
                {
                    FirstFrameNumber = 1,
                    TgaFrameSizeBytes = (int)sizes[0]
                }
            },
            frameRate);

        Assert.False(result.Success);
        Assert.Contains("record length", result.ErrorMessage!, StringComparison.Ordinal);
    }

    /// <summary>
    ///     The audio really is on the output, at the length the video is - which is what the duration
    ///     guard is checking for in the abstract, confirmed here against a real container.
    /// </summary>
    [Fact]
    public async Task TheMuxedClipsAudioAndVideoAgreeOnLength()
    {
        FfmpegTools.SkipUnlessAvailable();

        const int frameCount = 48;
        const int frameRate = 24;
        const double seconds = frameCount / (double)frameRate;

        FfmpegTools.GenerateFrameSequence(_source.Path, "jpg", frameCount, frameRate);
        FfmpegTools.GenerateSilentWav(Path.Combine(_source.Path, "csvg_000.wav"), seconds);

        CaptureResult result = await RunAsync(
            new InEngineCaptureConfiguration
            {
                FrameFormat = InEngineFrameFormat.Jpg,
                FrameConsumerPollMs = 20,
                IntermediateEncoder = ImagePipeEncoder.X264,
                EngineOutput = new InEngineEngineOutput { FirstFrameNumber = 1 }
            },
            frameRate);

        Assert.True(result.Success, result.ErrorMessage);
        Assert.Empty(result.Warnings);

        double videoSeconds = FfmpegTools.StreamDuration(result.OutputFilePath, "v:0");
        double audioSeconds = FfmpegTools.StreamDuration(result.OutputFilePath, "a:0");
        Assert.Equal(seconds, videoSeconds, 1);
        Assert.Equal(seconds, audioSeconds, 1);
    }

    /// <summary>
    ///     A real wav read by the hand-rolled RIFF parser rather than by ffprobe: the guard's whole
    ///     value depends on the number it reads meaning the same thing ffmpeg thinks it does.
    /// </summary>
    [Fact]
    public void ARealWavsHeaderIsReadTheSameWayFfprobeReadsIt()
    {
        FfmpegTools.SkipUnlessAvailable();

        string wavPath = Path.Combine(_audio.Path, "probe.wav");
        FfmpegTools.GenerateSilentWav(wavPath, 3.5);

        WavHeader? header = InEngineAudioLocator.TryReadHeader(wavPath);

        Assert.NotNull(header);
        Assert.True(header.IsFinalized);
        Assert.Equal(FfmpegTools.StreamDuration(wavPath, "a:0"), header.Duration.TotalSeconds, 2);
    }

    /// <summary>
    ///     Runs a clip whose frames are copied in from <see cref="_source" /> while the encoder is
    ///     armed, standing in for the engine writing them.
    /// </summary>
    private async Task<CaptureResult> RunAsync(InEngineCaptureConfiguration configuration, int frameRate)
    {
        FfmpegService ffmpeg = new(NullLogger<FfmpegService>.Instance, Options.Create(new FfmpegOptions()));

        InEngineCaptureSession session = new(
            configuration,
            new CaptureSessionContext { Engine = new FakeEngineConsole() },
            ffmpeg,
            () => _staging.Path,
            () => _audio.Path);

        await using (session)
        {
            await session.InitializeAsync(Ct);

            ClipCaptureContext context = new()
            {
                StartTick = 1000,
                EndTick = 1640,
                ClipIndex = 0,
                Metadata = new CaptureMetadata
                {
                    OutputFileName = "clip_000",
                    OutputDirectory = _output.Path,
                    FrameRate = frameRate
                }
            };

            IClipCapture clip = await session.BeginClipAsync(context, Ct);
            await clip.OnPlaybackStartingAsync(Ct);

            // Everything the engine would write, written while the clip is armed - which is also what
            // the clip's written-after check on the wav requires. The frames go into a
            // timestamp-named subdirectory with 8-digit numbering, which is the layout CS2 was
            // observed writing; the generator's 4-digit source names are re-padded to match.
            string movieDirectory = Path.Combine(_staging.Path,
                InEngineTestHarness.TimestampedSubdirectoryName);
            Directory.CreateDirectory(movieDirectory);

            foreach (string source in Directory.GetFiles(_source.Path).Order())
            {
                string extension = Path.GetExtension(source);

                if (extension.Equals(".wav", StringComparison.Ordinal))
                {
                    File.Copy(source, Path.Combine(_audio.Path, Path.GetFileName(source)));
                    continue;
                }

                int number = int.Parse(Path.GetFileNameWithoutExtension(source)["frame".Length..],
                    CultureInfo.InvariantCulture);
                File.Copy(source, Path.Combine(movieDirectory,
                    $"csvg_000{number.ToString("D8", CultureInfo.InvariantCulture)}{extension}"));
            }

            await clip.OnPlaybackEndedAsync(Ct);
            return await clip.FinalizeAsync(Ct);
        }
    }
}
